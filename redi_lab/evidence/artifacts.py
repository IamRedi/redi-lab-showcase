"""Bounded immutable retention for verified handoff artifacts.

This is deliberately a small local evidence facility, not an object store.  A
coordinator calls :func:`retain_validated_artifact` only after validating the
worker workspace boundary and the source hash/size.  The retained relative
path can then be persisted in the handoff evidence and verified read-only
after ephemeral worker workspaces have been removed.
"""

from __future__ import annotations

import hashlib
import os
import re
import stat
from pathlib import Path, PurePosixPath


MAX_RETAINED_ARTIFACT_BYTES = 1024 * 1024

_FORBIDDEN_BYTE_MARKERS = (
    b"chain_of_thought",
    b"chain-of-thought",
    b"hidden_test",
    b"hidden-test",
    b"provider_response",
    b"raw_response",
)
_SECRET_RE = re.compile(rb"sk-[A-Za-z0-9_-]{8,}")


class ArtifactRetentionError(ValueError):
    """A retained artifact failed a boundedness or integrity requirement."""


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _safe_relative_path(value: str) -> PurePosixPath:
    if not isinstance(value, str) or not value.strip():
        raise ArtifactRetentionError("retained artifact path must be non-empty")
    if re.match(r"^[A-Za-z]:[\\/]", value) or value.startswith(("/", "\\", "~")):
        raise ArtifactRetentionError("retained artifact path must be relative")
    rel = PurePosixPath(value.replace("\\", "/"))
    if rel.is_absolute() or any(part in {"", ".", ".."} for part in rel.parts):
        raise ArtifactRetentionError("retained artifact path is unsafe")
    if not rel.parts or rel.parts[0] != "handoffs":
        raise ArtifactRetentionError("retained artifact must be under handoffs/")
    return rel


def _resolved_target(root: Path, rel: PurePosixPath) -> Path:
    root_resolved = root.resolve()
    target = (root_resolved / Path(*rel.parts)).resolve()
    try:
        target.relative_to(root_resolved)
    except ValueError as exc:
        raise ArtifactRetentionError("retained artifact escapes run artifact root") from exc
    return target


def retained_relative_path(artifact_id: str) -> str:
    """Return a safe deterministic filename without exposing artifact-id syntax."""
    if not isinstance(artifact_id, str) or not artifact_id.strip():
        raise ArtifactRetentionError("artifact_id must be non-empty")
    digest = hashlib.sha256(artifact_id.encode("utf-8")).hexdigest()
    return f"handoffs/{digest}.artifact"


def _reject_forbidden_content(data: bytes) -> None:
    lowered = data.lower()
    if any(marker in lowered for marker in _FORBIDDEN_BYTE_MARKERS):
        raise ArtifactRetentionError("retained artifact contains forbidden private material marker")
    if _SECRET_RE.search(data):
        raise ArtifactRetentionError("retained artifact contains a secret-like token")


def retain_validated_artifact(
    *,
    run_artifact_root: Path | str,
    source_path: Path | str,
    artifact_id: str,
    expected_sha256: str,
    expected_size: int,
    maximum_bytes: int = MAX_RETAINED_ARTIFACT_BYTES,
) -> str:
    """Copy exactly one validated file into the immutable run evidence area.

    The final file is created with exclusive-create semantics.  Existing
    targets are never overwritten, even if their bytes happen to match.
    """
    root = Path(run_artifact_root)
    source = Path(source_path)
    data = source.read_bytes()
    actual_size = len(data)
    actual_hash = _sha256(data)
    if actual_size > int(maximum_bytes):
        raise ArtifactRetentionError(
            f"artifact exceeds retained size bound: {actual_size} > {int(maximum_bytes)}"
        )
    if actual_size != int(expected_size):
        raise ArtifactRetentionError(
            f"retained source size mismatch: {actual_size} != {int(expected_size)}"
        )
    if actual_hash != str(expected_sha256).lower():
        raise ArtifactRetentionError("retained source hash mismatch")
    _reject_forbidden_content(data)

    return retain_generated_bytes_artifact(
        run_artifact_root=root,
        data=data,
        artifact_id=artifact_id,
        expected_sha256=actual_hash,
        expected_size=actual_size,
        maximum_bytes=maximum_bytes,
    )


def retain_generated_bytes_artifact(
    *,
    run_artifact_root: Path | str,
    data: bytes,
    artifact_id: str,
    expected_sha256: str,
    expected_size: int,
    maximum_bytes: int = MAX_RETAINED_ARTIFACT_BYTES,
) -> str:
    """Retain generated bytes under a deterministic, model-path-independent name.

    This is the same bounded immutable retention mechanism as
    :func:`retain_validated_artifact`, but avoids writing an ungoverned staging
    file first.  It is used for parsed builder output before any patch gate
    decides whether the generated path/action is acceptable.
    """
    if not isinstance(data, bytes):
        raise ArtifactRetentionError("generated artifact data must be bytes")
    actual_size = len(data)
    actual_hash = _sha256(data)
    if actual_size > int(maximum_bytes):
        raise ArtifactRetentionError(
            f"artifact exceeds retained size bound: {actual_size} > {int(maximum_bytes)}"
        )
    if actual_size != int(expected_size):
        raise ArtifactRetentionError(
            f"retained source size mismatch: {actual_size} != {int(expected_size)}"
        )
    if actual_hash != str(expected_sha256).lower():
        raise ArtifactRetentionError("retained source hash mismatch")
    _reject_forbidden_content(data)

    root = Path(run_artifact_root)
    rel_text = retained_relative_path(artifact_id)
    rel = _safe_relative_path(rel_text)
    target = _resolved_target(root, rel)
    target.parent.mkdir(parents=True, exist_ok=True)
    if target.exists():
        raise ArtifactRetentionError(f"retained artifact identity conflict: {artifact_id!r}")

    created = False
    try:
        with target.open("xb") as handle:
            created = True
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        copied = target.read_bytes()
        if len(copied) != actual_size or _sha256(copied) != actual_hash:
            raise ArtifactRetentionError("retained artifact copy verification failed")
        # POSIX mode hardening is useful, while Windows read-only files impede
        # deterministic run-directory cleanup.  Immutability is primarily
        # enforced by the exclusive-create/no-overwrite retention API; replay
        # independently detects any out-of-band tampering on every audit.
        if os.name != "nt":
            target.chmod(stat.S_IREAD)
    except Exception:
        if created and target.exists():
            try:
                target.chmod(stat.S_IWRITE | stat.S_IREAD)
                target.unlink()
            except OSError:
                pass
        raise
    return rel_text


def verify_retained_artifact(
    *,
    run_artifact_root: Path | str,
    retained_path: str,
    artifact_id: str,
    expected_sha256: str,
    expected_size: int,
    maximum_bytes: int = MAX_RETAINED_ARTIFACT_BYTES,
) -> dict[str, object]:
    """Read-only post-hoc verification of one retained artifact."""
    expected_path = retained_relative_path(artifact_id)
    if retained_path != expected_path:
        raise ArtifactRetentionError("retained artifact path does not bind to artifact identity")
    rel = _safe_relative_path(retained_path)
    target = _resolved_target(Path(run_artifact_root), rel)
    if not target.is_file():
        raise ArtifactRetentionError(f"retained artifact is missing: {retained_path!r}")
    data = target.read_bytes()
    actual_size = len(data)
    if actual_size > int(maximum_bytes):
        raise ArtifactRetentionError("retained artifact exceeds size bound")
    actual_hash = _sha256(data)
    if actual_size != int(expected_size):
        raise ArtifactRetentionError("retained artifact size mismatch")
    if actual_hash != str(expected_sha256).lower():
        raise ArtifactRetentionError("retained artifact hash mismatch")
    _reject_forbidden_content(data)
    return {
        "artifact_id": artifact_id,
        "retained_path": retained_path,
        "sha256": actual_hash,
        "size_bytes": actual_size,
    }


